function snapshot = recording_metadata(session, settings, activity)
  snapshot = struct('schema', 'industrial-drive.sesiune.v2', ...
    'sursa', session.sursa, 'session_id', session.id, 'segment_id', session.segment_id, ...
    'orchestrator_id', settings.orchestrator_id, 'actualizat_epoch', time(), ...
    'esantion_epoch', session.esantion_epoch, 'sim_time_s', session.ultim_s, ...
    'achizitie', activity, 'stare', session.stare, 'numar_esantioane', session.numar, ...
    'alarme_active', {session.alarme}, 'unitati', struct('t_s','s', 'rpm','RPM', ...
    'phase_current_a','A', 'rms_est_a','A', 'vdc_v','V', 'f_ref_hz','Hz'));
  snapshot.praguri_informative = settings.diagnostic;
  write_json_atomic([session.baza '_meta.json'], snapshot);
  write_json_atomic(fullfile(settings.director_rezultate, ['stare_' session.sursa '.json']), snapshot);
endfunction
