function valid = validate_command(request, settings)
  valid = false;
  try
    valid = strcmp(request.orchestrator_id,settings.orchestrator_id) && ...
      isscalar(request.secventa) && isfinite(request.secventa) && request.secventa > 0 && fix(request.secventa) == request.secventa && ...
      isscalar(request.expira_epoch) && isfinite(request.expira_epoch) && request.expira_epoch >= time() && ...
      isscalar(request.pornit) && islogical(request.pornit) && any(strcmp(request.mod,{'manual','profil'})) && ...
      isscalar(request.frecventa_hz) && isfinite(request.frecventa_hz) && request.frecventa_hz >= 0 && request.frecventa_hz <= settings.control.frecventa_max_hz && ...
      isscalar(request.sarcina_nm) && isfinite(request.sarcina_nm) && request.sarcina_nm >= 0 && request.sarcina_nm <= settings.control.sarcina_max_nm && ...
      isscalar(request.acceleration_s) && isfinite(request.acceleration_s) && request.acceleration_s >= 1 && request.acceleration_s <= 30 && ...
      isscalar(request.deceleration_s) && isfinite(request.deceleration_s) && request.deceleration_s >= 2 && request.deceleration_s <= 60 && ...
      isscalar(request.reset) && islogical(request.reset) && !(request.reset && request.pornit);
  catch
    valid = false;
  end_try_catch
endfunction
